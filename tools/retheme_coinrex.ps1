$targets = @('assets/css', 'admin/assets/css', 'devhub/assets/css')
$changed = 0

foreach ($target in $targets) {
  Get-ChildItem -Path $target -Recurse -Filter *.css | ForEach-Object {
    $path = $_.FullName
    $content = Get-Content -Path $path -Raw
    $original = $content

    foreach ($key in $repls.Keys) {
      $content = $content.Replace($key, $repls[$key])
    }

    if ($content -ne $original) {
      Set-Content -Path $path -Value $content -NoNewline
      $changed++
    }
  }
}

Write-Output ("updated files: $changed")